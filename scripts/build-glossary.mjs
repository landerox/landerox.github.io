/** Publish the single bilingual catalog as searchable, linkable Markdown. */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { URL, fileURLToPath } from "node:url";
import { validateGlossary } from "../content/en/assets/javascripts/glossary-core.js";
import { normalize } from "../content/en/assets/javascripts/text-core.js";

const terms = validateGlossary(JSON.parse(readFileSync(
  new URL("../content/en/assets/glossary.json", import.meta.url), "utf8",
)));
const byId = new Map(terms.map((term) => [term.id, term]));
const copy = {
  en: {
    title: "Technical glossary",
    description: "Cloud, platform, data and AI concepts with practical examples, caveats, related terms and primary sources.",
    introduction: "Look up a concept, follow its connections, or try it in a local tool. Each definition includes an example, a limitation and a primary source.",
    domain: { cloud: "Cloud", platform: "Platform", data: "Data", ai: "AI" },
    example: "In practice", caveat: "Watch for", related: "Related concepts",
    source: "Read the source", link: "Link to this definition",
    practice: "Try it", tools: "Explore all six tools", toolsPath: "projects/tools.md",
  },
  es: {
    title: "Glosario técnico",
    description: "Conceptos de cloud, plataforma, datos e IA con ejemplos prácticos, límites, términos relacionados y fuentes primarias.",
    introduction: "Consulta un concepto, sigue sus conexiones o pruébalo en una herramienta local. Cada definición incluye un ejemplo, una limitación y una fuente primaria.",
    domain: { cloud: "Cloud", platform: "Plataforma", data: "Datos", ai: "IA" },
    example: "En la práctica", caveat: "Ten en cuenta", related: "Conceptos relacionados",
    source: "Leer la fuente", link: "Enlace a esta definición",
    practice: "Pruébalo", tools: "Explorar las seis herramientas", toolsPath: "projects/tools.md",
  },
};
const escape = (text) => text.replace(/[\\`*_[\]<>]/g, "\\$&");
const wrap = (text) => text.split(" ").reduce((lines, word) => {
  if (lines.at(-1).length + word.length + 1 > 78) lines.push(word);
  else lines[lines.length - 1] += (lines.at(-1) ? " " : "") + word;
  return lines;
}, [""]).join("\n");
const sortKey = normalize;
let stale = false;
for (const locale of ["en", "es"]) {
  const t = copy[locale];
  const url = `https://landerox.com/${locale === "es" ? "es/" : ""}glossary/`;
  const sorted = [...terms].sort((a, b) => {
    const left = sortKey(a[locale].term), right = sortKey(b[locale].term);
    return left < right ? -1 : left > right ? 1 : 0;
  });
  const lines = [
    "---", `description: ${JSON.stringify(t.description)}`,
    "icon: material/book-open-variant", "hide:", "  - toc", "---", "",
    "<!-- Generated by scripts/build-glossary.mjs; edit assets/glossary.json. -->", "",
    `# :material-book-open-variant: ${t.title}`, "", wrap(t.introduction), "",
    `[${t.tools}](${t.toolsPath}).`, "",
    '<div class="glossary-page" data-glossary-page markdown>', "",
    '<div class="glossary-page-controls"></div>', "",
    '<div class="glossary-entries" markdown>', "",
  ];
  for (const term of sorted) {
    const text = term[locale];
    lines.push(
      `<section class="glossary-entry" data-term-id="${term.id}"`,
      `data-category="${term.category}" markdown>`, "",
      `## ${escape(text.term)} {#${term.id}}`, "",
      `<p class="glossary-entry-domain">${t.domain[term.category]}</p>`, "",
      wrap(escape(text.definition)), "",
      wrap(`**${t.example}.** ${escape(text.example)}`), "",
      wrap(`**${t.caveat}.** ${escape(text.caveat)}`), "",
      `<p class="glossary-related" markdown>`, "",
      `**${t.related}:**`,
      ...term.related.map((id, index) =>
        `[${escape(byId.get(id)[locale].term)}](#${id})${index < term.related.length - 1 ? " ·" : ""}`),
      "", "</p>", "",
      wrap(`[${t.source} · ${escape(term.source.label)}](${term.source.url})`), "",
      `[${t.link}](#${term.id})`, "",
    );
    if (term.practice) lines.push(
      `[${t.practice}: ${escape(term.practice[locale])}](projects/tools.md#${term.practice.path.split("#")[1]})`, "",
    );
    lines.push("</section>", "");
  }
  const structured = {
    "@context": "https://schema.org", "@type": "DefinedTermSet",
    "@id": url, name: t.title, inLanguage: locale,
    hasDefinedTerm: sorted.map((term) => ({
      "@type": "DefinedTerm", "@id": `${url}#${term.id}`,
      name: term[locale].term, description: term[locale].definition,
      inDefinedTermSet: url,
    })),
  };
  lines.push("</div>", "", "</div>", "",
    "<!-- markdownlint-disable MD013 -->",
    '<script type="application/ld+json">',
    JSON.stringify(structured, null, 2).replace(/</g, "\\u003c"),
    "</script>", "<!-- markdownlint-enable MD013 -->", "");
  const output = lines.join("\n");
  const destination = new URL(`../content/${locale}/glossary.md`, import.meta.url);
  if (globalThis.process.argv.includes("--check")) {
    let existing = "";
    try { existing = readFileSync(destination, "utf8"); }
    catch { /* A missing generated page is stale too. */ }
    if (existing !== output) {
      console.error(`Stale glossary: ${fileURLToPath(destination)}. Run just glossary.`);
      stale = true;
    }
  } else writeFileSync(destination, output);
}
// Acronym tooltips for every page, appended by pymdownx.snippets. The theme's
// content.tooltips feature renders the abbr titles.
for (const locale of ["en", "es"]) {
  const entries = terms
    .flatMap((term) => Object.entries(term.abbr || {}).map(([key, value]) =>
      `*[${key}]: ${value[locale]}: ${term[locale].definition}`))
    .sort((a, b) => sortKey(a) < sortKey(b) ? -1 : sortKey(a) > sortKey(b) ? 1 : 0);
  // No comments: this file is appended to every page's Markdown.
  const output = [...entries, ""].join("\n");
  const destination = new URL(`../includes/${locale}/abbreviations.md`, import.meta.url);
  if (globalThis.process.argv.includes("--check")) {
    let existing = "";
    try { existing = readFileSync(destination, "utf8"); }
    catch { /* A missing generated file is stale too. */ }
    if (existing !== output) {
      console.error(`Stale abbreviations: ${fileURLToPath(destination)}. Run just glossary.`);
      stale = true;
    }
  } else {
    mkdirSync(new URL(".", destination), { recursive: true });
    writeFileSync(destination, output);
  }
}
if (stale) globalThis.process.exitCode = 1;
else console.log(`Glossary: ${terms.length} terms in EN and ES.`);
